using System; // подключаем базовые команды для консоли

class Program // стандартный класс программы как на паре
{ // открываем фигурные скобки класса
    static void Main() // главная функция откуда запускается код
    { // открываем тело программы
        Console.WriteLine("Введите первое число:"); // пишем на экран текст чтобы человек понял что вводить
        double num1 = Convert.ToDouble(Console.ReadLine()); // читаем строчку с клавиатуры и переделываем в число num1

        Console.WriteLine("Введите знак операции (+, -, *, /):"); // спрашиваем какой знак действия нужен
        char op = Convert.ToChar(Console.ReadLine()); // считываем один знак операции и кладем в переменную op

        Console.WriteLine("Введите второе число:"); // просим ввести следующее число
        double num2 = Convert.ToDouble(Console.ReadLine()); // читаем второе число и тоже переводим из текста в double

        if (op == '+') // если ввели плюс то идем складывать
        { // открываем блок для плюса
            Console.WriteLine($"Результат: {num1 + num2}"); // считаем сумму и выводим ответ
        } // закрываем действие плюса
        else if (op == '-') // если вместо плюса ввели минус
        { // открываем блок минуса
            Console.WriteLine($"Результат: {num1 - num2}"); // отнимаем от первого второе и выводим на экран
        } // закрываем действие минуса
        else if (op == '*') // если выбрали умножение
        { // открываем блок умножения
            Console.WriteLine($"Результат: {num1 * num2}"); // перемножаем оба числа и выводим на экран
        } // закрываем умножение
        else if (op == '/') // если выбрали операцию деления
        { // заходим в блок деления
            if (num2 == 0) // по заданию проверяем чтобы второе число не оказалось нулем
            { // блок если ввели ноль
                Console.WriteLine("Ошибка: на ноль делить нельзя!"); // пишем ошибку
            } // конец проверки нуля
            else // если второе число нормальное и не ноль
            { // блок обычного деления
                Console.WriteLine($"Результат: {num1 / num2}"); // делим num1 на num2 и выводим
            } // закрываем обычное деление
        } // закрываем весь блок с делением
        else // если пользователь ввел вообще какой-то левый символ
        { // блок для неизвестного знака
            Console.WriteLine("Ошибка: неверная операция!"); // сообщаем что такой операции калькулятор не знает
        } // закрываем блок ошибки
    } // закрываем метод Main
} // закрываем класс Program
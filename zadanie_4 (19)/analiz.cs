using System; // подключаем базовые системные команды

class Program // создаем обычный класс программы
{ // открываем класс
    static void Main() // главный метод откуда запускается программа
    { // открываем тело программы
        Console.WriteLine("Введите текст или предложение:"); // выводим подсказку пользователю
        string text = Console.ReadLine(); // читаем напечатанную строку

        int wordCount = 0; // счетчик количества найденных слов
        int totalLetters = 0; // сумма длин всех слов чтобы потом посчитать среднее
        string longestWord = ""; // строка куда запишем самое длинное найденное слово
        string currentWord = ""; // временная строка для сборки текущего слова по буквам

        int i = 0; // заводим счетчик для обхода строки с первого символа
        while (i < text.Length) // крутим цикл пока не дойдем до конца введенного текста
        { // открываем тело цикла while
            char c = text[i]; // берем очередной символ из строки по индексу i

            if (char.IsLetterOrDigit(c)) // проверяем является ли символ буквой или цифрой
            { // если это часть слова
                currentWord += c; // дописываем эту букву к текущему собираемому слову
            } // конец блока буквы
            else // если встретили пробел запятую точку или другой разделитель
            { // блок окончания слова
                if (currentWord.Length > 0) // проверяем накопилось ли в переменной хоть одно слово
                { // если слово действительно закончилось
                    wordCount++; // прибавляем единицу к количеству слов
                    totalLetters += currentWord.Length; // добавляем длину этого слова в общую копилку букв

                    if (currentWord.Length > longestWord.Length) // если текущее слово длиннее сохраненного
                    { // блок обновления рекорда
                        longestWord = currentWord; // запоминаем его как новое самое длинное
                    } // конец проверки длины

                    currentWord = ""; // сбрасываем слово в пустоту чтобы собирать следующее
                } // конец проверки непустого слова
            } // конец блока разделителя

            i++; // сдвигаем указатель к следующему символу строки
        } // закрываем цикл while

        if (currentWord.Length > 0) // отдельно проверяем последнее слово если в конце текста не было пробела
        { // обрабатываем хвост предложения
            wordCount++; // учитываем последнее слово
            totalLetters += currentWord.Length; // прибавляем его длину к общей сумме букв

            if (currentWord.Length > longestWord.Length) // проверяем не оказалось ли оно самым длинным
            { // блок рекорда для последнего слова
                longestWord = currentWord; // обновляем самое длинное слово
            } // конец проверки последнего слова
        } // конец обработки хвоста

        Console.WriteLine("\n--- Результаты анализа ---"); // печатаем красивый заголовок
        Console.WriteLine($"Количество слов: {wordCount}"); // выводим общее число слов
        Console.WriteLine($"Самое длинное слово: {longestWord}"); // выводим самое длинное слово

        if (wordCount > 0) // проверяем чтобы не делить на ноль если пользователь ввел пустую строку
        { // если слова есть
            double avgLength = (double)totalLetters / wordCount; // делим общее число букв на количество слов
            Console.WriteLine($"Средняя длина слова: {avgLength:F1}"); // печатаем среднюю длину с одной цифрой после запятой
        } // конец блока подсчета среднего
        else // если слов вообще не ввели
        { // блок для пустого текста
            Console.WriteLine("Слова в тексте не найдены."); // пишем предупреждение
        } // конец проверки на отсутствие слов
    } // закрываем метод Main
} // закрываем класс Program
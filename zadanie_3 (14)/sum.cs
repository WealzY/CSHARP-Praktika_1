using System; // подключаем базовые команды для консоли

class Program // объявляем класс
{ // открываем класс
    static void Main() // главный метод программы
    { // открываем метод Main
        int sum = 0; // создаем переменную для суммы, сначала в ней ноль
        int number; // переменная куда будем сохранять очередное введенное число

        Console.WriteLine("Вводите числа (для завершения введите 0):"); // пишем подсказку для пользователя

        do // запускаем цикл do-while, который точно выполнится хотя бы один раз
        { // открываем тело цикла
            number = Convert.ToInt32(Console.ReadLine()); // читаем число с клавиатуры
            sum = sum + number; // прибавляем полученное число к нашей переменной sum
        } while (number != 0); // условие: крутить цикл дальше, пока введенное число не равно 0

        Console.WriteLine($"Сумма введенных чисел: {sum}"); // выводим на экран итоговую сумму
    } // закрываем метод Main
} // закрываем класс Program